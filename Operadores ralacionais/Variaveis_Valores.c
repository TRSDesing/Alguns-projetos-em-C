#include <stdio.h>

int main(){
    int a = 10;
    int b = 5;

    int x = 5;
    float y = 5.0;

    printf("a > b: %d\n", a > b);
    printf("a < b: %d\n", a < b);
    printf("a >= b: %d\n", a >= b);
    printf("a <= b: %d\n", a <= b);
    printf("a == b: %d\n", a == b);
    printf("a != b: %d\n\n", a != b); //O operador "!=" é o operador de diferente.

    printf("x > y: %d\n", x > y);
    printf("x < y: %d\n", x < y);
    printf("x >= y: %d\n", x >= y);
    printf("x <= y: %d\n", x <= y);
    printf("x == y: %d\n", x == y);
    printf("x != y: %d\n", x != y);

    return 0;
}

